# --- 2. DATA LOADING (CACHED) ---
@st.cache_data
def load_data():
    # Carga de los 3 archivos que subiste a GitHub
    df_group_preds = pd.read_csv('WC26_GroupStage_Predictions.csv')
    df_str = pd.read_csv('WC26_Team_Strengths.csv').set_index('Team')
    df_timeline = pd.read_csv('WC26_Full_Tournament_Profiles.csv')
    return df_group_preds, df_str, df_timeline

df_group_preds, df_str, df_timeline = load_data()
teams_list = sorted(df_str.index.tolist())

# --- 3. TABS CREATION ---
tab1, tab2, tab3 = st.tabs(["📊 The Oracle (10k Simulations)", "⚔️ Match Predictor", "🌌 Multiverse Explorer"])

